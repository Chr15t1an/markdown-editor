#!/usr/bin/env python3
"""Generate registry.swift: an explicit list of every `func test*` in Tests/MarkdownCoreTests.

Swift has no method reflection and the test classes are not @objc, so the runner cannot discover
tests at runtime (verified: class_copyMethodList on a shim-XCTestCase subclass lists no test* methods).
This script re-derives the list from the sources on every run, so adding a test needs no manual step.

Usage: gen-registry.py <tests-dir> <out-file>
"""
import re
import sys
from pathlib import Path

CLASS_RE = re.compile(r'^\s*(?:final\s+)?class\s+(\w+)\s*:\s*XCTestCase\b')
TEST_RE = re.compile(r'^\s+(?:@\w+\s+)*func\s+(test\w*)\s*\(\s*\)\s*(async)?\s*(throws)?')


def collect(tests_dir: Path):
    files = []
    for path in sorted(tests_dir.glob('*.swift')):
        classes = []
        current = None
        for line in path.read_text().splitlines():
            m = CLASS_RE.match(line)
            if m:
                current = {'name': m.group(1), 'tests': []}
                classes.append(current)
                continue
            m = TEST_RE.match(line)
            if m and current is not None:
                current['tests'].append((m.group(1), bool(m.group(2)), bool(m.group(3))))
        files.append((path.name, classes))
    return files


def emit(files, out: Path):
    lines = [
        '// GENERATED by gen-registry.py — do not edit. Regenerated on every scripts/test.sh run.',
        'import XCTest',
        '@testable import MarkdownCore',
        '@testable import MarkdownEditor',
        '',
        '@MainActor',
        'func runRegisteredTests() async {',
    ]
    for file_name, classes in files:
        for cls in classes:
            lines.append(f'    await TestRunner.run({cls["name"]}.self, "{cls["name"]}", file: "{file_name}", tests: [')
            for name, is_async, throws in cls['tests']:
                call = f't.{name}()'
                if is_async:
                    call = 'await ' + call
                if throws:
                    call = 'try ' + call
                lines.append(f'        ("{name}", {{ t in {call} }}),')
            lines.append('    ])')
    lines.append('}')
    out.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    tests_dir, out = Path(sys.argv[1]), Path(sys.argv[2])
    files = collect(tests_dir)
    emit(files, out)
    total = sum(len(c['tests']) for _, cs in files for c in cs)
    print(f'registry: {total} tests in {sum(len(cs) for _, cs in files)} classes across {len(files)} files -> {out}')
